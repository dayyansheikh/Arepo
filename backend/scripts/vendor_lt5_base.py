def normalised_sha(src: str) -> str:
    return hashlib.sha256(PREFIX.sub("", src).encode("utf-8")).hexdigest()


def main() -> None:
    parts, prov = [HEADER], {}
    for fname, names in PICK.items():
        text = (HERE / fname).read_text()
        fsha = hashlib.sha256(text.encode("utf-8")).hexdigest()
        tree = ast.parse(text)
        nodes = {n.name: n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
        parts.append(f"\n\n# --- from {fname} (sha256 {fsha[:16]}...) " + "-" * 40 + "\n")
        for name in names:
            src = ast.get_source_segment(text, nodes[name])
            parts.append("\n\n" + PREFIX.sub("", src) + "\n")
            prov[name] = {"source": fname, "source_sha256": fsha, "normalised_sha256": normalised_sha(src)}
    parts.append("\n\nVENDORED = " + json.dumps(prov, indent=1, sort_keys=True) + "\n")
    OUT.write_text("".join(parts))
    print(f"wrote {OUT} ({len(prov)} names)")


if __name__ == "__main__":
    main()
