#!/usr/bin/env python3
# ruff: noqa: E501, UP031, UP032, UP015, UP004, UP028  (Python 3.6-compatible style, shared with archive_rotate.py)
"""Regenerate the data catalogue in docs/research_lab/data_catalogue/ from the releases in the private data repo.

For every published release `data-*` in dayyansheikh/arepo-data it reads (via `gh`) MANIFEST.sha256, files.sha256
(checked against MANIFEST), ARCHIVE_INFO.json, VERIFY.json and, when present, files.bytes.json, and writes

  <out>/<tag>.jsonl   one row per file (release, path, dir, capture_id, capture_time_utc, bytes, sha256, experiments)
                      -- releases with more than --group-over files get one row per capture folder instead
                      (granularity "group": n_files + sha256 of the sorted listing); their per-file hashes stay in
                      the release's files.sha256, which restore_from_archive.py always uses
  <out>/releases.json machine-readable summary per release
  <out>/README.md     the human table between the BEGIN/END RELEASES markers (the rest of the file is kept)

Idempotent: running it twice gives identical files. Never writes outside --out. Drafts are skipped unless
--include-draft (a draft is not verified).

  python3 scripts/archive_catalogue.py                 # all data-* releases
  python3 scripts/archive_catalogue.py --tag data-20261015-dsheikh
"""

import argparse
import importlib.util
import json
import os
import shutil
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
import sys  # noqa: E402

sys.path.insert(0, HERE)
import archive_release as ar  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "data_catalogue", os.path.join(HERE, "..", "astrolabe", "research_lab", "data_catalogue.py")
)
dc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dc)

MAC_TAGS = {
    "data-20261011",
    "data-20261013-fs2",
    "data-20261013-research-lab",
    "data-20261014-research-lab-tail",
}
BEGIN, END = "<!-- BEGIN RELEASES (generated by archive_catalogue.py) -->", "<!-- END RELEASES -->"
DEFAULT_OUT = os.path.join(REPO_ROOT, "docs", "research_lab", "data_catalogue")


def list_tags(repo):
    out = ar.run(["gh", "release", "list", "-R", repo, "--limit", "200", "--json", "tagName,isDraft"])[1]
    return sorted((r["tagName"], r["isDraft"]) for r in json.loads(out) if r["tagName"].startswith("data-"))


def fetch(repo, tag, dest):
    os.makedirs(dest, exist_ok=True)
    pats = ["MANIFEST.sha256", "files.sha256", "ARCHIVE_INFO.json", "VERIFY.json", "files.bytes.json"]
    cmd = ["gh", "release", "download", tag, "-R", repo, "-D", dest, "--clobber"]
    for p in pats:
        cmd += ["-p", p]
    ar.run(cmd)
    man = {}
    for ln in open(os.path.join(dest, "MANIFEST.sha256")):
        h, n = ln.rstrip("\n").split("  ", 1)
        man[n] = h
    if ar.sha256_file(os.path.join(dest, "files.sha256")) != man.get("files.sha256"):
        raise SystemExit("%s: files.sha256 does not match MANIFEST.sha256" % tag)
    files = {}
    for ln in open(os.path.join(dest, "files.sha256")):
        h, p = ln.rstrip("\n").split("  ", 1)
        files[p] = h

    def js(name):
        p = os.path.join(dest, name)
        return json.load(open(p)) if os.path.exists(p) else None

    return man, files, js("ARCHIVE_INFO.json"), js("VERIFY.json"), js("files.bytes.json")


def created_at(repo, tag):
    out = ar.run(["gh", "release", "view", tag, "-R", repo, "--json", "createdAt,publishedAt,isDraft"])[1]
    return json.loads(out)


def summarize(tag, repo, files, rows, info, ver, meta, sizes):
    caps = sorted(r["capture_time_utc"] for r in rows if r.get("capture_time_utc"))
    days = sorted(r["date_utc"] for r in rows if r.get("date_utc"))
    exps = sorted({e for r in rows for e in r.get("experiments") or []})
    dirs = {}
    for r in rows:
        d = r.get("dir") or "(other)"
        dirs[d] = dirs.get(d, 0) + (r.get("n_files") or 1)
    if info and info.get("logical_bytes") is not None:
        nbytes = info["logical_bytes"]
    elif sizes:
        nbytes = sum(sizes.get(p, 0) for p in files)
    else:
        nbytes = None
    src = "mac" if tag in MAC_TAGS else "host"
    if ver is None:
        vstat = "no VERIFY.json (pre-dates the verify report; hashes in files.sha256)"
    else:
        vstat = ("PASS" if ver.get("passed") else "FAIL") + " %s (%s/%s members)" % (
            ver.get("verified_utc", "")[:19] + "Z", ver.get("n_members_verified"), ver.get("n_listed"))
    return {
        "tag": tag,
        "repo": repo,
        "created_utc": meta["createdAt"],
        "source": src,
        "source_root": (info or {}).get("base"),
        "source_host": (info or {}).get("host"),
        "dirs": dict(sorted(dirs.items())),
        "capture_time_first": caps[0] if caps else None,
        "capture_time_last": caps[-1] if caps else None,
        "date_first": days[0] if days else None,
        "date_last": days[-1] if days else None,
        "n_files": len(files),
        "bytes": nbytes,
        "compressed_bytes": (info or {}).get("compressed_bytes"),
        "experiments": exps,
        "verify": vstat,
        "granularity": "group" if rows and rows[0].get("granularity") == "group" else "file",
        "restore": "python3 backend/scripts/restore_from_archive.py --tag %s --dest <empty dir> [--dir D] [--experiment E] [--since T] [--until T] [--path-glob G]" % tag,
    }


def fmt_bytes(n):
    if n is None:
        return "n/a"
    return "%.2f GB" % (n / 1e9) if n >= 1e9 else "%.1f MB" % (n / 1e6)


def render_table(summaries):
    out = [BEGIN, ""]
    out.append("| tag | created (UTC) | source | source root | dirs (files) | capture time range | files | bytes | experiments | verify |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for s in sorted(summaries, key=lambda s: (s["created_utc"], s["tag"])):
        rng = "n/a"
        if s["capture_time_first"]:
            rng = "%s .. %s" % (s["capture_time_first"], s["capture_time_last"])
        elif s["date_first"]:
            rng = "days %s .. %s" % (s["date_first"], s["date_last"])
        dirs = ", ".join("%s (%d)" % (d, n) for d, n in s["dirs"].items())
        if len(dirs) > 300:
            top = sorted(s["dirs"].items(), key=lambda kv: -kv[1])[:6]
            dirs = ", ".join("%s (%d)" % kv for kv in top) + ", ... (%d dirs; see %s.jsonl)" % (len(s["dirs"]), s["tag"])
        out.append(
            "| `%s` | %s | %s | `%s` | %s | %s | %d | %s | %s | %s |"
            % (
                s["tag"], s["created_utc"], s["source"] + (" (%s)" % s["source_host"] if s["source_host"] else ""),
                s["source_root"] or "n/a", dirs, rng, s["n_files"], fmt_bytes(s["bytes"]),
                ", ".join(s["experiments"]) or "-", s["verify"],
            )
        )
    out += ["", "Experiment ids:", ""]
    used = sorted({e for s in summaries for e in s["experiments"]})
    for e in used:
        out.append("- `%s`: %s" % (e, dc.EXPERIMENT_LABELS.get(e, "")))
    out += ["", END]
    return "\n".join(out) + "\n"


def write_readme(path, table):
    if os.path.exists(path):
        txt = open(path).read()
        if BEGIN in txt and END in txt:
            pre = txt.split(BEGIN)[0]
            post = txt.split(END, 1)[1]
            new = pre + table.rstrip("\n") + post
        else:
            new = txt.rstrip("\n") + "\n\n" + table
    else:
        new = "# Data catalogue\n\n" + table
    if not os.path.exists(path) or open(path).read() != new:
        with open(path, "w") as o:
            o.write(new)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default="dayyansheikh/arepo-data")
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--tag", action="append", help="only these tags (repeatable); default all data-* releases")
    ap.add_argument("--include-draft", action="store_true")
    ap.add_argument("--group-over", type=int, default=20000, help="releases with more files get per-capture-folder rows")
    a = ap.parse_args(argv)
    os.makedirs(a.out, exist_ok=True)
    idx_path = os.path.join(a.out, "releases.json")
    index = {}
    if os.path.exists(idx_path):
        for s in json.load(open(idx_path)):
            index[s["tag"]] = s
    tmp = tempfile.mkdtemp(prefix="arepo_cat_")
    try:
        for tag, draft in list_tags(a.repo):
            if a.tag and tag not in a.tag:
                continue
            if draft and not a.include_draft:
                print("skip draft %s" % tag)
                continue
            man, files, info, ver, sizes = fetch(a.repo, tag, os.path.join(tmp, tag))
            meta = created_at(a.repo, tag)
            src = "mac" if tag in MAC_TAGS else "host"
            if len(files) > a.group_over:
                rows = dc.build_group_rows(tag, files, source=src)
            else:
                rows = dc.build_rows(tag, files, sizes=sizes, source=src)
            with open(os.path.join(a.out, tag + ".jsonl"), "w") as o:
                o.write(dc.dump_jsonl(rows))
            index[tag] = summarize(tag, a.repo, files, rows, info, ver, meta, sizes)
            print("catalogued %s: %d files, %d rows" % (tag, len(files), len(rows)))
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    summaries = [index[t] for t in sorted(index)]
    with open(idx_path, "w") as o:
        json.dump(summaries, o, indent=1, sort_keys=True)
        o.write("\n")
    write_readme(os.path.join(a.out, "README.md"), render_table(summaries))
    unmapped = sorted({r["dir"] for t in index for r in dc.load_jsonl(os.path.join(a.out, t + ".jsonl"))
                       if not r.get("experiments") and r.get("dir")})
    if unmapped:
        print("dirs with no experiment mapping: %s" % unmapped)
    return 0


if __name__ == "__main__":
    sys.exit(main())
